"""Download SEC fundamentals for every S&P 500 member since 2009 and build the monthly
fundamental signal panel. Run after build_data.py. Cached per company in data/raw/sec/.

    python scripts/build_fundamentals.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd

from factorlab import fundamentals, paths, signals

FUND_SIGNALS = paths.DATA / "fundamental_signals.parquet"


def main() -> None:
    uni = pd.read_parquet(paths.UNIVERSE)
    uni = uni[uni["month_end"] >= "2009-01-31"]
    print(f"1/3 SEC companyfacts for {uni['ticker'].nunique()} tickers (members since 2009)")
    info = fundamentals.build(uni["ticker"].unique().tolist())
    print(f"  mapped {info['mapped']}/{info['requested']}, no usable XBRL: {len(info['empty'])}")

    print("2/3 monthly fundamental panel")
    monthly = pd.read_parquet(paths.MONTHLY)
    daily = pd.read_parquet(paths.PRICES_DAILY, columns=["date", "ticker", "split"])
    annual = pd.read_parquet(fundamentals.FUND_ANNUAL)
    shares = pd.read_parquet(fundamentals.SHARES)
    panel = signals.fundamental_panel(monthly, daily, annual, shares)
    panel.to_parquet(FUND_SIGNALS)

    print("3/3 coverage report")
    write_coverage(uni, panel, info)


def write_coverage(uni, panel, info) -> None:
    m = uni.set_index(["month_end", "ticker"]).join(panel, how="left")
    by_year = m.groupby(m.index.get_level_values("month_end").year).agg(
        member_months=("mcap", "size"),
        mcap=("mcap", lambda s: s.notna().mean()),
        book_to_market=("book_to_market", lambda s: s.notna().mean()),
        gross_prof=("gross_prof", lambda s: s.notna().mean()),
        asset_growth=("asset_growth", lambda s: s.notna().mean()),
    )
    L = [
        "# Fundamentals coverage",
        "",
        "Generated by `scripts/build_fundamentals.py`. Share of point-in-time S&P 500 member-months "
        "with each fundamental field. Gaps come from (1) XBRL starting in 2009, (2) SEC's ticker map "
        "only covering current tickers, so most former members are unmapped, and (3) companies that "
        "don't report a concept (banks have no gross profit).",
        "",
        f"- Tickers in the index since 2009: **{info['requested']}**; mapped to a CIK: "
        f"**{info['mapped']}**; mapped but no usable annual XBRL: **{len(info['empty'])}**",
        f"- Unmapped (mostly acquired or delisted): {', '.join(info['unmapped'][:60])}"
        + (" ..." if len(info["unmapped"]) > 60 else ""),
        "",
        "| Year | Member-months | Market cap | Book-to-market | Gross profitability | Asset growth |",
        "|---|---|---|---|---|---|",
    ]
    for y, r in by_year.iterrows():
        L.append(f"| {y} | {int(r.member_months):,} | {r.mcap:.1%} | {r.book_to_market:.1%} | "
                 f"{r.gross_prof:.1%} | {r.asset_growth:.1%} |")
    (paths.REPORTS / "fundamentals_coverage.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"  overall market-cap coverage {m['mcap'].notna().mean():.1%} of member-months since 2009")


if __name__ == "__main__":
    main()
