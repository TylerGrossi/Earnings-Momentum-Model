"""Pipeline check: do our factors reproduce the published Ken French factors?

If the data and timing are right, the S&P 500 equal-weighted return should track the French
market return closely, and our momentum and reversal long-short portfolios should correlate
clearly with French's UMD and ST_Rev. They won't match exactly: French uses all US stocks,
value-weighted 2x3 sorts; we use S&P 500 members, equal-weighted quintiles.

    python scripts/validate_factors.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from factorlab import evaluate, paths, signals

FUND_SIGNALS = paths.DATA / "fundamental_signals.parquet"
WINDOWS = [("2000-01-31", "full sample"), ("2010-01-31", "2010 on, better coverage")]


def main() -> None:
    parts = []
    for start, label in WINDOWS:
        print(f"\n=== {label} (from {start[:7]}) ===")
        parts.append(run(start, label, chart=(start == WINDOWS[0][0])))
    if FUND_SIGNALS.exists():
        label = "Fundamental signals (SEC XBRL), 2011 on"
        print(f"\n=== {label} ===")
        parts.append(run("2011-01-31", label, chart=False, fundamental=True))
    L = [
        "# Factor validation against Ken French",
        "",
        "Generated by `scripts/validate_factors.py`. Ours: S&P 500 members at formation, "
        "equal-weighted quintiles, long top minus short bottom, monthly rebalance, no costs. "
        "French: all US stocks, value-weighted 2x3 sorts. Free price data covers about half of "
        "members before 2005 and 90%+ after 2021 (see data_coverage.md), so the 2010+ window is "
        "the more trustworthy one.",
        "",
    ]
    for p in parts:
        L += p
    L += ["![validation](factor_validation.png)", ""]
    (paths.REPORTS / "factor_validation.md").write_text("\n".join(L), encoding="utf-8")


def run(START: str, label: str, chart: bool, fundamental: bool = False) -> list[str]:
    uni = pd.read_parquet(paths.UNIVERSE)
    monthly = pd.read_parquet(paths.MONTHLY)
    ff = pd.read_parquet(paths.FRENCH)
    monthly = monthly[monthly["month_end"] >= "1995-01-31"]

    # Market check: equal-weighted return of index members vs French market.
    mem = monthly.merge(uni, on=["month_end", "ticker"])
    ew = mem.groupby("month_end")["ret"].mean()
    mkt = ff["Mkt-RF"] + ff["RF"]
    both = pd.concat([ew.rename("ours"), mkt.rename("ff")], axis=1).dropna().loc[START:]
    mkt_corr = both.corr().iloc[0, 1]

    if fundamental:
        fp = pd.read_parquet(FUND_SIGNALS)
        # (name, signal, French factor, sign so that high = expected to outperform)
        specs = [
            ("Book-to-market (value)", fp["book_to_market"], "HML", +1),
            ("Earnings yield", fp["earnings_yield"], "HML", +1),
            ("Operating profitability", fp["op_prof"], "RMW", +1),
            ("Gross profitability", fp["gross_prof"], "RMW", +1),
            ("Asset growth (investment)", fp["asset_growth"], "CMA", -1),
            ("Size (log market cap)", fp["size"], "SMB", -1),
        ]
    else:
        specs = [
            ("Momentum 12-1", signals.momentum_12_1(monthly), "UMD", +1),
            ("1-month reversal", signals.reversal_1m(monthly), "STREV", -1),
        ]
    rows, ls_series = [], {}
    for name, sig, ff_col, sign in specs:
        df = evaluate.attach_forward(sig * sign, monthly, uni)
        df = df[df.index.get_level_values("month_end") >= START]
        ic = evaluate.rank_ic(df)
        q = evaluate.quantile_returns(df)
        ls = (q[5] - q[1]).rename(name)
        ls_series[name] = ls
        j = pd.concat([ls, ff[ff_col]], axis=1).dropna()
        corr = j.corr().iloc[0, 1]
        beta = np.polyfit(j[ff_col], j[name], 1)[0]
        p = evaluate.perf_stats(ls)
        s = evaluate.ic_stats(ic)
        rows.append({"signal": name, "benchmark": ff_col, "corr": corr, "beta": beta,
                     "ls_ann_return": p["ann_return"], "ls_sharpe": p["sharpe"], "ls_t": p["t_stat"],
                     "ls_max_dd": p["max_drawdown"], "mean_rank_ic": s["mean_ic"], "ic_t": s["t_stat"],
                     "months": p["months"], "quintile_means": q.mean().round(4).to_dict()})
        ff_p = evaluate.perf_stats(ff[ff_col].loc[j.index])
        rows[-1]["ff_ann_return"] = ff_p["ann_return"]
        rows[-1]["ff_sharpe"] = ff_p["sharpe"]

    res = pd.DataFrame(rows)
    print(f"Market: corr(EW S&P members, French Mkt) = {mkt_corr:.3f} over {len(both)} months")
    print(res.drop(columns="quintile_means").round(3).to_string(index=False))

    if chart:
        fig, axes = plt.subplots(1, len(specs), figsize=(12, 4))
        for ax, (name, _, ff_col, _) in zip(axes, specs):
            j = pd.concat([ls_series[name], ff[ff_col]], axis=1).dropna()
            (1 + j).cumprod().plot(ax=ax, logy=True)
            ax.set_title(f"{name} vs French {ff_col}")
            ax.legend(["Ours (S&P 500, EW Q5-Q1)", f"French {ff_col}"], fontsize=8)
            ax.set_xlabel("")
        fig.tight_layout()
        fig.savefig(paths.REPORTS / "factor_validation.png", dpi=120)

    return section(res, mkt_corr, len(both), both.index.min(), both.index.max(), label)


def section(res, mkt_corr, n, first, last, label) -> list[str]:
    L = [
        f"## {label}: {first:%Y-%m} to {last:%Y-%m}",
        "",
        f"**Market check:** equal-weighted S&P 500 members vs French market return, "
        f"correlation {mkt_corr:.3f} over {n} months.",
        "",
        "| Signal | French factor | Correlation | Beta | Our L/S ann. return | Our Sharpe | Our t | "
        "French ann. return | French Sharpe | Mean rank IC | IC t |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in res.itertuples():
        L.append(f"| {r.signal} | {r.benchmark} | {r.corr:.2f} | {r.beta:.2f} | {r.ls_ann_return:+.1%} | "
                 f"{r.ls_sharpe:.2f} | {r.ls_t:.2f} | {r.ff_ann_return:+.1%} | {r.ff_sharpe:.2f} | "
                 f"{r.mean_rank_ic:.3f} | {r.ic_t:.2f} |")
    L += ["", "Quintile mean monthly returns (1 = lowest signal):", ""]
    for r in res.itertuples():
        L.append(f"- {r.signal}: " + ", ".join(f"Q{k}: {v:+.2%}" for k, v in r.quintile_means.items()))
    L.append("")
    return L


if __name__ == "__main__":
    main()
