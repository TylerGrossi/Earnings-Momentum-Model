"""Pre-registered Tests A and B (see PREREGISTRATION.md). Writes reports/test_results.md.

    python scripts/run_tests.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import warnings

warnings.filterwarnings("ignore")

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from factorlab import fundamentals, paths, portfolio, preprocess, research, signals

COST_BPS = 10
A_START = "2012-01-31"
B_START = "2014-01-31"


def verdict_a(ic_t: float, ls_t: float) -> str:
    if ic_t >= 2 and ls_t >= 2:
        return "FINDING (both t >= 2)"
    if ic_t < 1 and ls_t < 1:
        return "NO EFFECT (both t < 1)"
    return "WEAK / INCONCLUSIVE"


def verdict_b(sharpe: float, t: float) -> str:
    return "FINDING (net Sharpe > 0, t >= 2)" if sharpe > 0 and t >= 2 else "NOT A FINDING"


def main() -> None:
    uni = pd.read_parquet(paths.UNIVERSE)
    monthly = pd.read_parquet(paths.MONTHLY)
    ff = pd.read_parquet(paths.FRENCH)
    sec = pd.read_csv(paths.DATA / "sectors.csv")
    eq = pd.read_parquet(fundamentals.EARNINGS_Q)

    raw = preprocess.raw_panel(monthly, uni)
    month_ends = raw.index.get_level_values("month_end").unique()
    sue = signals.sue(eq, month_ends).rename("sue")
    members = pd.MultiIndex.from_frame(uni[["month_end", "ticker"]])
    sue = sue[sue.index.isin(members)]
    raw = raw.join(sue, how="left")
    preprocess.SIGNS["sue"] = +1
    raw = raw[raw.index.get_level_values("month_end") >= "2011-01-31"]
    panel = preprocess.clean_panel(raw, sec, neutralize=True)
    f1 = preprocess.forward_returns(monthly, [1]).reindex(panel.index)["fwd_1"]

    L = ["# Pre-registered test results", "",
         "Generated by `scripts/run_tests.py`. Definitions and criteria: "
         "[PREREGISTRATION.md](../PREREGISTRATION.md). Costs 10 bps per unit traded; Newey-West t-stats.", ""]

    # ---- Test A ----
    s = panel["sue"]
    s = s[s.index.get_level_values("month_end") >= A_START]
    coverage = s.notna().groupby(level="month_end").mean().mean()
    ic = research.monthly_rank_ic(s, f1)
    ic_mean, ic_t = research.newey_west_t(ic)
    ls = research.long_short(s, f1, cost_bps=COST_BPS)
    g, n = research.perf(ls["gross"]), research.perf(ls["net"])
    att = research.attribution(ls["net"], ff)
    va = verdict_a(ic_t, n["nw_t"])
    print(f"Test A: IC {ic_mean:.4f} t {ic_t:.2f} | gross {g['ann_return']:+.2%} net {n['ann_return']:+.2%} "
          f"t {n['nw_t']:.2f} sharpe {n['sharpe']:.2f} | alpha {att['alpha_ann']:+.2%} t {att['alpha_nw_t']:.2f} -> {va}")
    decay = {h: research.monthly_rank_ic(s, preprocess.forward_returns(monthly, [h]).reindex(s.index)[f"fwd_{h}"]).mean()
             for h in (1, 2, 3, 6)}
    L += ["## Test A: earnings surprise (SUE), S&P 500", "",
          f"Formation months {A_START[:7]} to {s.index.get_level_values('month_end').max():%Y-%m}; "
          f"signal available for {coverage:.0%} of member-months on average (a quarter filed in the prior 92 days).", "",
          "| Measure | Value |", "|---|---|",
          f"| Mean rank IC (t) | {ic_mean:.4f} ({ic_t:.2f}) |",
          f"| Long-short gross / net, per year | {g['ann_return']:+.2%} / {n['ann_return']:+.2%} |",
          f"| Net Sharpe (Newey-West t) | {n['sharpe']:.2f} ({n['nw_t']:.2f}) |",
          f"| Long leg / short leg mean monthly return | {ls['long'].mean():+.2%} / {ls['short'].mean():+.2%} |",
          f"| Monthly turnover (share of book) | {ls['turnover'].mean() / 2:.0%} |",
          f"| Alpha vs FF5 + momentum, per year (t) | {att['alpha_ann']:+.2%} ({att['alpha_nw_t']:.2f}) |",
          f"| Months | {n['months']} |",
          f"| IC at t+1 / t+2 / t+3 / t+6 | " + " / ".join(f"{decay[h]:.4f}" for h in decay) + " |",
          "", f"**Verdict: {va}.**", ""]

    # Secondary (not used for verdict): SUE added to equal-weight composite.
    base = [c for c in panel.columns if c != "sue"]
    comp9 = research.combo_equal(panel[base])
    comp10 = research.combo_equal(panel)
    sec_rows = []
    for name, sc in [("Composite, 9 signals", comp9), ("Composite + SUE, 10 signals", comp10)]:
        sc = sc[sc.index.get_level_values("month_end") >= B_START]
        l2 = research.long_short(sc, f1, cost_bps=COST_BPS)
        p = research.perf(l2["net"])
        sec_rows.append(f"| {name} | {research.monthly_rank_ic(sc, f1).mean():.4f} | {p['ann_return']:+.2%} | {p['sharpe']:.2f} | {p['nw_t']:.2f} |")
    L += ["Secondary, not used for the verdict: SUE added to the equal-weight composite "
          f"({B_START[:7]} on).", "", "| Composite | Mean IC | Net per year | Net Sharpe | t |",
          "|---|---|---|---|---|", *sec_rows, ""]

    # ---- Test B ----
    comp = comp9[comp9.index.get_level_values("month_end") >= B_START]
    variants = {"Monthly quintiles (first pass, reference)": portfolio.quintile(comp),
                "3-month overlapping holding": portfolio.overlapping(comp, 3),
                "Banding 20% in / 40% out": portfolio.banded(comp, 0.2, 0.4)}
    L += ["## Test B: lower-turnover construction of the 9-signal composite, S&P 500", "",
          f"Out-of-sample {B_START[:7]} on. The reference row is the first-pass construction, not a test variant.", "",
          "| Construction | Gross per year | Net per year | Net Sharpe | Net t | Monthly turnover | Verdict |",
          "|---|---|---|---|---|---|---|"]
    curves = {}
    for name, w in variants.items():
        r = portfolio.run(w, f1, COST_BPS)
        g2, n2 = research.perf(r["gross"]), research.perf(r["net"])
        v = "reference" if name.startswith("Monthly") else verdict_b(n2["sharpe"], n2["nw_t"])
        print(f"Test B {name}: gross {g2['ann_return']:+.2%} net {n2['ann_return']:+.2%} sharpe {n2['sharpe']:.2f} "
              f"t {n2['nw_t']:.2f} turnover {r['turnover'].mean() / 2:.0%} -> {v}")
        L.append(f"| {name} | {g2['ann_return']:+.2%} | {n2['ann_return']:+.2%} | {n2['sharpe']:.2f} | "
                 f"{n2['nw_t']:.2f} | {r['turnover'].mean() / 2:.0%} | {v} |")
        curves[name] = r["net"]
    curves["Test A: SUE long-short"] = ls["net"][ls.index >= pd.Timestamp(B_START)]
    L += ["", "![tests](test_results.png)", ""]

    fig, ax = plt.subplots(figsize=(9, 4.5))
    for name, r in curves.items():
        (1 + r).cumprod().plot(ax=ax, label=name)
    ax.axhline(1, color="grey", lw=0.8)
    ax.set_title(f"Net of {COST_BPS} bps, long-short, S&P 500")
    ax.legend(fontsize=8)
    ax.set_xlabel("")
    fig.tight_layout()
    fig.savefig(paths.REPORTS / "test_results.png", dpi=120)
    (paths.REPORTS / "test_results.md").write_text("\n".join(L), encoding="utf-8")


if __name__ == "__main__":
    main()
