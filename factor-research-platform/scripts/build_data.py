"""Build every data file: universe, daily and monthly prices, Ken French factors, coverage report.

    python scripts/build_data.py           # uses cached downloads where present
    python scripts/build_data.py --fresh   # re-download membership and French files
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd

from factorlab import french, paths, prices, universe

START = "1996-01-31"


def main(fresh: bool) -> None:
    print("1/4 membership + universe")
    universe.download_membership(force=fresh)
    uni = universe.monthly_universe(start=START)
    uni.to_parquet(paths.UNIVERSE, index=False)
    print(f"  {uni['month_end'].nunique()} months, {uni['ticker'].nunique()} tickers ever in index")

    print("2/4 daily prices (yfinance, cached per chunk)")
    daily = prices.download_daily(uni["ticker"].unique().tolist(), start="1995-01-01")
    daily.to_parquet(paths.PRICES_DAILY, index=False)

    print("3/4 monthly panel")
    monthly = prices.build_monthly(daily)
    monthly.to_parquet(paths.MONTHLY, index=False)

    print("4/4 Ken French factors")
    ff = french.download_all()
    print(f"  {ff.index.min():%Y-%m} to {ff.index.max():%Y-%m}, columns {list(ff.columns)}")

    write_coverage(uni, monthly)


def write_coverage(uni: pd.DataFrame, monthly: pd.DataFrame) -> None:
    """How much of the true index we actually have prices for, by year. This is the honest
    measure of survivorship bias in the free data."""
    have = monthly.dropna(subset=["ret"])[["month_end", "ticker"]].assign(has_ret=True)
    cov = uni.merge(have, on=["month_end", "ticker"], how="left")
    cov["has_ret"] = cov["has_ret"].notna()
    by_year = cov.groupby(cov["month_end"].dt.year)["has_ret"].agg(["mean", "size"])
    ever = uni["ticker"].nunique()
    no_px = pd.read_csv(paths.PRICE_MISSING)["ticker"].nunique() if paths.PRICE_MISSING.exists() else 0
    # Extreme monthly returns are usually data errors (bad splits) or ticker reuse.
    m = monthly.merge(uni, on=["month_end", "ticker"])
    extreme = m[(m["ret"] > 1.0) | (m["ret"] < -0.8)]

    lines = [
        "# Data coverage",
        "",
        "Generated by `scripts/build_data.py`. Measures how much of the point-in-time S&P 500 the "
        "free price data (yfinance) covers. Missing member-months are mostly stocks that were later "
        "delisted, acquired or went bankrupt, so results are biased toward survivors by roughly the "
        "missing share.",
        "",
        f"- Tickers ever in the index since {START[:4]}: **{ever}**",
        f"- Tickers with no Yahoo prices at all: **{no_px}** ({no_px / ever:.1%})",
        f"- Member-months with a monthly return: **{cov['has_ret'].mean():.1%}** of {len(cov):,}",
        f"- Member-months with a return above +100% or below -80%: **{len(extreme)}** "
        "(checked by hand before trusting results)",
        f"- Excluded as bad data (`prices.BAD_TICKERS`): "
        + "; ".join(f"**{t}** ({why})" for t, why in prices.BAD_TICKERS.items()),
        "",
        "| Year | Member-months | With return |",
        "|---|---|---|",
    ]
    lines += [f"| {y} | {int(r['size']):,} | {r['mean']:.1%} |" for y, r in by_year.iterrows()]
    if len(extreme):
        lines += ["", "## Extreme monthly returns among members", "", "| Month | Ticker | Return |", "|---|---|---|"]
        lines += [f"| {r.month_end:%Y-%m} | {r.ticker} | {r.ret:+.1%} |"
                  for r in extreme.sort_values("month_end").itertuples()]
    (paths.REPORTS / "data_coverage.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  coverage {cov['has_ret'].mean():.1%} of member-months; report in reports/data_coverage.md")


if __name__ == "__main__":
    main(fresh="--fresh" in sys.argv)
