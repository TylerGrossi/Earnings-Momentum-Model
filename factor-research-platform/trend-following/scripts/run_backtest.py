"""Run the pre-specified trend-following backtest (README.md).

    python scripts/run_backtest.py             # development sample, Jan 2007 - Dec 2022
    python scripts/run_backtest.py --holdout   # holdout Jan 2023 on, plus full 2007-latest; run once
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import warnings

warnings.filterwarnings("ignore")

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from trend import data, stats, strategy

HOLDOUT = "--holdout" in sys.argv
DEV = ("2007-01-31", "2022-12-31")
HOLD_START = "2023-01-31"
PRIMARY = "TSMOM 12m (primary)"
SECONDARY = "TSMOM 1/3/12m blend (secondary)"


def pct(x):
    return "n/a" if pd.isna(x) else f"{x:+.1%}"


def table(rows: list[list], header: list[str]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header),
            *["| " + " | ".join(str(c) for c in r) + " |" for r in rows]]


def main() -> None:
    px = data.download()
    rf_d = data.daily_rf(px)
    inp = strategy.build_inputs(px, rf_d)
    RF = inp["RF"]

    sigs = strategy.signals(inp["EX"])
    W = {k: strategy.weights(s, inp) for k, s in sigs.items()}
    bt = {k: strategy.backtest(w, inp) for k, w in W.items()}
    bt_cost = {c: strategy.backtest(W[PRIMARY], inp, cost_bps=c) for c in (5, 20)}

    # Benchmarks (total monthly returns).
    r_d = px.pct_change(fill_method=None)
    Rall = strategy.monthly_returns(r_d[["SPY", "IEF"] + list(data.FUNDS)])
    spy, ief = Rall["SPY"], Rall["IEF"]
    sixty40 = 0.6 * spy + 0.4 * ief
    series = {k: v["total"] for k, v in bt.items()}
    series["SPY"] = spy
    series["60/40 (SPY/IEF)"] = sixty40
    series["80/20: 80% 60/40 + 20% trend"] = 0.8 * sixty40 + 0.2 * bt[PRIMARY]["total"]

    if HOLDOUT:
        windows = {"Holdout": (HOLD_START, "2100-01-01"), "Full": (DEV[0], "2100-01-01")}
    else:
        windows = {"Development": DEV}
    # Cut everything to the last evaluated month before computing any statistic.
    last = max(e for _, e in windows.values())
    series = {k: v[(v.index >= DEV[0]) & (v.index <= last)].dropna() for k, v in series.items()}
    common = series[PRIMARY].index
    series = {k: v.reindex(common) for k, v in series.items()}
    rf = RF.reindex(common)

    L = [f"# Trend following results: {' + '.join(windows)}", "",
         "Generated by `scripts/run_backtest.py`" + (" --holdout" if HOLDOUT else "") +
         ". Design fixed in advance in README.md. Strategy returns are net of 10 bps per unit "
         "traded and a 0.5%/yr short-borrow fee; Sharpe uses excess returns over T-bills; "
         "t-stats are Newey-West (6 lags). Backtest only, ETF proxies, no live trading.", ""]

    for wname, (ws, we) in windows.items():
        sel = lambda s: s[(s.index >= ws) & (s.index <= we)]
        rows = []
        for k, s in series.items():
            s = sel(s).dropna()
            m = stats.summary(s, s - rf.reindex(s.index))
            rows.append([k, f"{m['start']} to {m['end']}", pct(m["cagr"]), f"{m['vol']:.1%}",
                         f"{m['sharpe']:.2f}", f"{m['nw_t']:.2f}", pct(m["max_dd"]),
                         f"{pct(m['worst_year'])} ({m['worst_year_label']})"])
        L += [f"## {wname} sample", ""]
        L += table(rows, ["Series", "Period", "CAGR", "Vol", "Sharpe", "t", "Max DD", "Worst year"])
        L.append("")
        print(f"\n{wname}:")
        for r in rows:
            print("  " + " | ".join(r))

    ws, we = list(windows.values())[-1]
    sel = lambda s: s[(s.index >= ws) & (s.index <= we)]
    p = sel(series[PRIMARY])

    # Cost sensitivity.
    rows = []
    for c, b in [(5, bt_cost[5]), (10, bt[PRIMARY]), (20, bt_cost[20])]:
        e = sel(b["excess"].reindex(common))
        rows.append([f"{c} bps", f"{e.mean() / e.std() * np.sqrt(12):.2f}", pct(sel(b["total"].reindex(common)).add(1).prod() ** (12 / len(e)) - 1)])
    L += ["## Cost sensitivity (primary)", ""] + table(rows, ["Cost per unit traded", "Sharpe", "CAGR"]) + [""]

    # Trading stats.
    b = bt[PRIMARY].reindex(common)
    b = sel(b)
    L += ["## Positioning (primary)", "",
          f"Average gross exposure {b['gross'].mean():.0%} of capital (max {b['gross'].max():.0%}); "
          f"average net long {b['net_long'].mean():+.0%}; average monthly turnover {b['turnover'].mean():.0%}; "
          f"average cost drag {b['cost'].mean() * 12:.2%}/yr plus borrow {b['borrow'].mean() * 12:.2%}/yr; "
          f"assets held: {b['n_assets'].min()} to {b['n_assets'].max()}.", ""]

    # Crisis windows.
    crises = [("2008", "2008-01-31", "2008-12-31"), ("2020 Q1", "2020-01-31", "2020-03-31"),
              ("2022", "2022-01-31", "2022-12-31"), ("2023-latest", "2023-01-31", "2100-01-01")]
    rows = []
    for name, cs, ce in crises:
        if pd.Timestamp(cs) > p.index.max() or pd.Timestamp(ce) < p.index.min():
            continue
        rows.append([name] + [pct(stats.window_return(series[k], cs, ce)) for k in
                              [PRIMARY, SECONDARY, "SPY", "60/40 (SPY/IEF)", "80/20: 80% 60/40 + 20% trend"]])
    L += ["## Crisis and stress windows", ""] + table(rows, ["Window", "Trend 12m", "Trend blend", "SPY", "60/40", "80/20"]) + [""]

    # Correlations.
    L += ["## Correlations of monthly returns (primary)", "",
          f"- With SPY: {p.corr(sel(series['SPY'])):.2f}",
          f"- With 60/40: {p.corr(sel(series['60/40 (SPY/IEF)'])):.2f}",
          f"- Primary with secondary: {p.corr(sel(series[SECONDARY])):.2f}", ""]

    # Validation against live funds.
    rows = []
    for f, name in data.FUNDS.items():
        fr = Rall[f].reindex(common)
        j = pd.concat([p, sel(fr)], axis=1).dropna()
        if len(j) < 12:
            continue
        fe = j.iloc[:, 1] - rf.reindex(j.index)
        pe = j.iloc[:, 0] - rf.reindex(j.index)
        rows.append([f"{f} ({name})", f"{j.index.min():%Y-%m} to {j.index.max():%Y-%m}", len(j),
                     f"{j.corr().iloc[0, 1]:.2f}",
                     f"{pe.mean() / pe.std() * np.sqrt(12):.2f}", f"{fe.mean() / fe.std() * np.sqrt(12):.2f}"])
    L += ["## Validation against live managed-futures funds", "",
          "Correlation of monthly total returns over each fund's overlapping history. Fund returns are "
          "after their fees; ours are after modelled costs only.", ""]
    L += table(rows, ["Fund", "Overlap", "Months", "Correlation", "Our Sharpe (same months)", "Fund Sharpe"]) + [""]
    for r in rows:
        print("  validation:", " | ".join(str(x) for x in r))

    # Asset-class contributions.
    cls = [c for c in b.columns if c.startswith("cls_")]
    contrib = b[cls].mean() * 12
    rows = [[c[4:], pct(v)] for c, v in contrib.sort_values(ascending=False).items()]
    L += ["## Return by asset class (primary, before costs, annualized)", ""] + table(rows, ["Class", "Contribution"]) + [""]

    # Sub-periods.
    subs = [("2007-2014", "2007-01-31", "2014-12-31"), ("2015-latest", "2015-01-31", "2100-01-01")]
    rows = []
    for name, ss, se in subs:
        for k in [PRIMARY, SECONDARY, "SPY", "60/40 (SPY/IEF)"]:
            s = series[k][(series[k].index >= ss) & (series[k].index <= se)].dropna()
            if len(s) < 12:
                continue
            m = stats.summary(s, s - rf.reindex(s.index))
            rows.append([name, k, f"{m['start']} to {m['end']}", pct(m["cagr"]), f"{m['sharpe']:.2f}", f"{m['nw_t']:.2f}", pct(m["max_dd"])])
    L += ["## Sub-periods", ""] + table(rows, ["Period", "Series", "Months", "CAGR", "Sharpe", "t", "Max DD"]) + [""]

    # Calendar years.
    cy = stats.calendar_years({k: series[k] for k in [PRIMARY, SECONDARY, "SPY", "60/40 (SPY/IEF)", "80/20: 80% 60/40 + 20% trend"]})
    cy = cy.dropna(how="all")
    rows = [[y] + [pct(v) for v in r] for y, r in cy.iterrows()]
    L += ["## Calendar years", ""] + table(rows, ["Year", "Trend 12m", "Trend blend", "SPY", "60/40", "80/20"]) + [""]

    # Chart.
    fig, axes = plt.subplots(2, 1, figsize=(10, 7), sharex=True, gridspec_kw={"height_ratios": [2, 1]})
    for k in [PRIMARY, "SPY", "60/40 (SPY/IEF)", "80/20: 80% 60/40 + 20% trend"]:
        w = (1 + series[k].dropna()).cumprod()
        w.plot(ax=axes[0], label=k, logy=True)
        (w / w.cummax() - 1).plot(ax=axes[1], label=k)
    axes[0].legend(fontsize=8)
    axes[0].set_title("Growth of $1 (log scale)")
    axes[1].set_title("Drawdown")
    axes[1].set_xlabel("")
    fig.tight_layout()
    tag = "holdout" if HOLDOUT else "development"
    fig.savefig(data.REPORTS / f"{tag}.png", dpi=120)
    L += [f"![results]({tag}.png)", ""]
    data.REPORTS.mkdir(exist_ok=True)
    (data.REPORTS / f"{tag}.md").write_text("\n".join(L), encoding="utf-8")


if __name__ == "__main__":
    main()
